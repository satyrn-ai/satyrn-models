"""Convert an independently authored task set into a scoreable benchmark.

Every result in this spike so far was measured on `benchmark/repair-v1`, which
is generated by `build_benchmark_v2.py` from the same task-template machinery
that generates the training curricula: same operation taxonomy, same
`Copy these input bindings` preamble, same three framings, same
`module-level variable result` contract. Every adapter memorizes its training
split (validation loss reaches ~0.005), so a score on that benchmark measures
transfer *within one synthetic distribution*. The documentation arms are the
only condition that was ever out-of-distribution relative to training — and
they win, which is exactly what that confound would predict.

This module scores an evaluation set authored by an agent with no access to
this repository: no sight of the benchmark, the curricula, the prompt
conventions, or the failure modes observed so far. Its independence was
verified before use — zero occurrences of nine tell-tale phrases, prompt
vocabulary Jaccard 0.111 against `repair-v1`, zero reference collisions
against 809 training answers, and a distinct answer variable per task where
`repair-v1` always uses `result`.

The one convention that cannot be removed is that the answer lives in a
module-level name, because `CheckSpec` is a closed union of `name_equals` and
`raises`. That is a property of the scoring mechanism rather than of our task
style, but it is shared and should be stated when reporting.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from satyrn_model.contracts import (
    CompleteProgram,
    GeneratedProvenance,
    NameEquals,
    PolicyRef,
    TaskRecord,
)

SOURCE = Path(
    "/Users/pauleveritt/projects/scratchpad/scratcharea/"
    "pep750_template_string_tasks.jsonl"
)

# `ood-v2`, authored to `spike/OOD_AUTHORING_SPEC.md`. The v1 set was
# independent but unusable: essentially every task required reference string
# literals its prompt never stated, so exact match graded literal-guessing. The
# spec adds the self-containment rule and a self-check the author must pass.
#
# Verified here rather than taken on trust:
#   - the spec's own self-check: 0 failing / 100
#   - vocabulary Jaccard 0.071 against `repair-v1` (v1 measured 0.111), 0.136
#     against the training curriculum
#   - zero occurrences of seven tell-tale phrases from our prompt conventions
#   - zero reference collisions against training answers
#   - 100 distinct answer variables, none named `result`
#   - answer types: 47 str, 53 non-str across dict/list/tuple/int and several
#     custom classes, so type-matching is informative rather than near-constant
#   - only 2 of 100 prompts yield no extractable literals, and no task is left
#     scoreable by policy alone
SOURCE_V2 = Path("/Users/pauleveritt/tmp/tstring-authoring/tasks.jsonl")


def build(source: Path = SOURCE) -> tuple[list[TaskRecord], list[dict[str, str]]]:
    """Wrap each authored task, preserving its prompt and answer name verbatim."""
    rows = [
        json.loads(line) for line in source.read_text().splitlines() if line.strip()
    ]
    tasks: list[TaskRecord] = []
    manifest: list[dict[str, str]] = []
    for index, row in enumerate(rows):
        task = TaskRecord(
            prompt=row["prompt"],
            reference=row["reference"],
            checks=(NameEquals(name=row["answer_variable"]),),
            policy=PolicyRef(
                id="tstring",
                version=1,
                config={
                    "requires_template": True,
                    "templatelib_apis": ["strings", "values"],
                },
            ),
            completion=CompleteProgram(),
            provenance=GeneratedProvenance(
                generator="independent-author",
                generator_version="1.0.0",
                seed_id=f"ood-{index}",
            ),
        )
        tasks.append(task)
        manifest.append(
            {
                "task_id": task.id,
                "capability": row["domain"],
                "operation": row["domain"],
                "role": "consumer",
                "family": "independently-authored",
                "framing": "natural",
                "answer_variable": row["answer_variable"],
                "review_status": "independently_authored",
            }
        )
    return tasks, manifest


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--out", type=Path, default=Path("benchmark/ood-v1"))
    args = parser.parse_args()

    tasks, manifest = build(args.source)
    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    with (out / "tasks.jsonl").open("w", encoding="utf-8") as stream:
        for task in tasks:
            stream.write(json.dumps(task.to_dict(), sort_keys=True) + "\n")
    (out / "manifest.json").write_text(
        json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8"
    )
    fingerprint = hashlib.sha256((out / "tasks.jsonl").read_bytes()).hexdigest()
    (out / "fingerprint.txt").write_text(fingerprint + "\n", encoding="utf-8")
    print(f"{out.name} tasks: {len(tasks)} ({fingerprint[:12]})")
